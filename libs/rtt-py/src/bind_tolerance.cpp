void bind_tolerance(nb::module_& m) {
  bind_enums(m);
  bind_classes(m);

  m.def(
      "tolerance_expand",
      [](const model::System& system, const material::MaterialLibrary* materials) {
        // A copy while the GIL is held, as for optimize (rt.System is mutable from Python).
        // NOLINTNEXTLINE(performance-unnecessary-copy-initialization): the copy is the point
        const model::System input = system;
        const material::MaterialLibrary default_materials;
        const material::MaterialLibrary& library =
            materials != nullptr ? *materials : default_materials;
        const nb::gil_scoped_release release;
        return tolerance::expand(input, library);
      },
      "system"_a, "materials"_a.none(),
      "The items of system.tolerances (ADR 0036, point 9). Raises CompileError for an invalid "
      "set or a glass of a generated abbe item that does not give nu_d.");
  m.def(
      "tolerance_class_limit",
      [](model::ToleranceClass tolerance_class, model::ToleranceKind kind,
         model::ToleranceLevel level) {
        if (kind == model::ToleranceKind::Abbe) {
          throw std::invalid_argument(
              "the class limit of abbe is relative to nu_d of the glass: use abbe_share() "
              "(the limit of a generated item is abbe_share(class) * nu_d, see expand)");
        }
        return tolerance::class_limit(tolerance_class, kind, level);
      },
      "tolerance_class"_a, "kind"_a, "level"_a,
      "The limit T of a generated item in the unit of the kind; ValueError for abbe.");
  m.def("tolerance_abbe_share", &tolerance::abbe_share, "tolerance_class"_a,
        "The share p of nu_d that limits abbe (SCHOTT TIE-29, steps 4, 3, 1).");
}

