/// A read-only class with value equality; not hashable, no constructor.
template <typename T>
nb::class_<T> read_only_class(nb::module_& m, const char* name, const char* doc) {
  nb::class_<T> cls(m, name, doc);
  cls.def("__eq__", &equal<T>, "other"_a);
  cls.attr("__hash__") = nb::none();
  return cls;
}

/// The name of the target at `anchor`, None at the other anchor (as ToleranceItem, #253).
std::optional<std::string> at(const model::ToleranceTarget& t, model::ToleranceAnchor anchor) {
  if (t.anchor != anchor) return std::nullopt;
  return t.name;
}

void bind_enums(nb::module_& m) {
  nb::enum_<model::ToleranceLevel>(
      m, "ToleranceLevel", "Level of a generated item; one class limit per class, kind and level.")
      .value("SURFACE", model::ToleranceLevel::Surface)
      .value("ELEMENT", model::ToleranceLevel::Element)
      .value("ASSEMBLY", model::ToleranceLevel::Assembly);
  nb::enum_<model::ClassSkip>(m, "ClassSkip",
                              "Why a class does not generate a kind at a target (ADR 0035, point "
                              "5); not an error.")
      .value("NONE", model::ClassSkip::None, "generated")
      .value("PLANE", model::ClassSkip::Plane,
             "curvature_relative or conic at a surface without a radius")
      .value("SPHERE", model::ClassSkip::Sphere, "conic at a sphere (conic constant 0)")
      .value("BOUND", model::ClassSkip::Bound,
             "the Param is bound to a row of the parameter table")
      .value("NO_MATERIAL_IN_BEAM", model::ClassSkip::NoMaterialInBeam,
             "index or abbe at an element other than lens and plate")
      .value("NO_MATERIAL", model::ClassSkip::NoMaterial,
             "index or abbe at a lens or plate without isotropic material")
      .value("CRYSTAL", model::ClassSkip::Crystal, "index or abbe at a crystal")
      .value("METAL", model::ClassSkip::Metal, "index or abbe at a CONST material with kappa > 0")
      .value("CONST_ABBE", model::ClassSkip::ConstAbbe,
             "abbe without dispersion (CONST, VACUUM or a glass with n_F = n_C)");
  nb::enum_<model::OverrideEffect>(m, "OverrideEffect",
                                   "What became of a single-value override (ADR 0035, point 5).")
      .value("APPLIED", model::OverrideEffect::Applied,
             "sets limit and distribution of a generated item")
      .value("CLASS_NONE", model::OverrideEffect::ClassNone, "no class at the target")
      .value("SKIPPED", model::OverrideEffect::Skipped, "the class skips the kind there")
      .value("REPLACED", model::OverrideEffect::Replaced,
             "an explicit item perturbs the same quantity")
      .value("NOT_GENERATED", model::OverrideEffect::NotGenerated,
             "no class generates the kind there");
  nb::enum_<tolerance::ItemOrigin::Source>(m, "ItemOriginSource", "Where an item comes from.")
      .value("CLASS", tolerance::ItemOrigin::Source::Class,
             "generated by a class; index into classes.items")
      .value("EXPLICIT", tolerance::ItemOrigin::Source::Explicit,
             "an explicit item; index into the items of the tolerance set");
}

void bind_classes(nb::module_& m) {
  using model::ClassTolerance;
  read_only_class<ClassTolerance>(
      m, "ClassTolerance", "One kind at one target that a class would generate (read-only copy).")
      .def_ro("id", &ClassTolerance::id,
              "\"class:node:<name>:<kind>[:<segment>]\" or \"class:surface:<id>:<kind>\".")
      .def_prop_ro(
          "surface",
          [](const ClassTolerance& c) { return at(c.target, model::ToleranceAnchor::Surface); },
          "Id of the target surface; None if the target is a node.")
      .def_prop_ro(
          "node", [](const ClassTolerance& c) { return at(c.target, model::ToleranceAnchor::Node); },
          "Name of the target element or assembly; None if the target is a surface.")
      .def_prop_ro(
          "segment", [](const ClassTolerance& c) { return c.target.segment; },
          "0-based segment for index and abbe of an element with several materials; None "
          "without.")
      .def_ro("kind", &ClassTolerance::kind, "The generated kind.")
      .def_ro("level", &ClassTolerance::level, "Surface, element or assembly.")
      .def_ro("tolerance_class", &ClassTolerance::tolerance_class,
              "The effective class: of the target or its nearest ancestor, else of the system.")
      .def_ro("value_override", &ClassTolerance::value_override,
              "Index of the single-value override in tolerances.overrides; None without.")
      .def_ro("replaced_by", &ClassTolerance::replaced_by,
              "Index of the explicit item in tolerances.items that perturbs the same quantity and "
              "takes precedence; None without.")
      .def_ro("skip", &ClassTolerance::skip, "Why the kind is skipped; NONE if not.")
      .def_prop_ro("generated", &ClassTolerance::generated,
                   "True if the item takes part in an analysis: not skipped, not replaced.");

  using model::OverrideStatus;
  read_only_class<OverrideStatus>(m, "OverrideStatus",
                                  "What became of one single-value override (read-only copy).")
      .def_ro("index", &OverrideStatus::index, "Index in tolerances.overrides.")
      .def_ro("effect", &OverrideStatus::effect, "Its effect.")
      .def_ro("skip", &OverrideStatus::skip, "The reason for SKIPPED; NONE otherwise.");

  nb::class_<model::ClassTolerances> classes(
      m, "ClassTolerances", "The enumeration of the classes (ADR 0035, point 5; read-only copy).");
  classes.attr("__hash__") = nb::none();
  classes
      .def_ro("items", &model::ClassTolerances::items,
              "Every kind at every target a class covers, in tree order, with skipped and "
              "replaced ones.")
      .def_ro("value_overrides", &model::ClassTolerances::value_overrides,
              "One entry per single-value override, in the order of tolerances.overrides.");

  using tolerance::ItemOrigin;
  read_only_class<ItemOrigin>(m, "ItemOrigin", "Where an item of ToleranceItems comes from.")
      .def_ro("source", &ItemOrigin::source, "CLASS or EXPLICIT.")
      .def_ro("index", &ItemOrigin::index,
              "CLASS: index in classes.items; EXPLICIT: index in the items of the tolerance set.");

  using tolerance::ToleranceItems;
  nb::class_<ToleranceItems> items(
      m, "ToleranceItems",
      "The complete item list of a tolerance set (ADR 0036, point 9; result of expand).");
  items.attr("__hash__") = nb::none();
  items
      .def_ro("items", &ToleranceItems::items,
              "The generated items in tree order, then the explicit items in file order. Limits "
              "in the unit of the kind (mm, degree, dimensionless).")
      .def_ro("origins", &ToleranceItems::origins, "Where each item comes from, same order.")
      .def_ro("classes", &ToleranceItems::classes,
              "The class enumeration, with the skipped and replaced kinds and their reasons.");
}

